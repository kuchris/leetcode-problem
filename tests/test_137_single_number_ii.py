"""Tests for 137. Single Number II.

Two oracles:

  - `counter_oracle` counts occurrences (the stated shape: one value once, every
    other value three times) and returns the count-1 value;
  - `runs_oracle` sorts and scans runs, returning the value whose run has length
    one. It is a second, structurally different reading of the same guarantee.

Both stay independent of the ones/twos bit automaton under test. Inputs are
generated by tripling a set of values and adding one value outside it, so they
always satisfy the guarantee.
"""

import itertools
import random
import unittest
from collections import Counter

from _loader import load_solution

Solution = load_solution('137-single-number-ii.py').Solution


def counter_oracle(nums: list[int]) -> int:
    counts = Counter(nums)
    for value, count in counts.items():
        if count == 1:
            return value
    raise AssertionError('no value appears exactly once')


def runs_oracle(nums: list[int]) -> int:
    ordered = sorted(nums)
    index = 0
    while index < len(ordered):
        run_end = index
        while run_end + 1 < len(ordered) and ordered[run_end + 1] == ordered[index]:
            run_end += 1
        if run_end == index:
            return ordered[index]
        index = run_end + 1
    raise AssertionError('no value appears exactly once')


def tripled_arrays(pool):
    """Arrays = three copies of a subset of `pool` plus one value outside it."""
    for size in range(len(pool) + 1):
        for chosen in itertools.combinations(pool, size):
            for single in pool:
                if single in chosen:
                    continue
                yield list(chosen) * 3 + [single]


class SingleNumberIITests(unittest.TestCase):
    def setUp(self):
        self.solve = Solution().singleNumber

    def check(self, nums, expected):
        self.assertEqual(self.solve(nums), expected)
        self.assertEqual(counter_oracle(nums), expected)
        self.assertEqual(runs_oracle(nums), expected)

    def test_official_examples(self):
        self.check([2, 2, 3, 2], 3)
        self.check([0, 1, 0, 1, 0, 1, 99], 99)

    def test_single_element(self):
        for value in (0, 1, -1, 2 ** 31 - 1, -2 ** 31):
            with self.subTest(value=value):
                self.check([value], value)

    def test_zero_and_negative_triples(self):
        self.check([0, 0, 0, 7], 7)
        self.check([-5, -5, -5, 0], 0)
        self.check([-1, -2, -1, -2, -1, -2, -3], -3)

    def test_boundary_values(self):
        self.check([-2 ** 31] * 3 + [2 ** 31 - 1], 2 ** 31 - 1)
        self.check([2 ** 31 - 1] * 3 + [-2 ** 31], -2 ** 31)
        self.check([-2 ** 31, 0, -2 ** 31, 0, -2 ** 31, 0, 2 ** 31 - 1], 2 ** 31 - 1)

    def test_high_bit_patterns(self):
        # Values whose bits interact: the automaton has to keep every bit
        # position independent.
        self.check([2 ** 30, -2 ** 30, 2 ** 30, -2 ** 30, 2 ** 30, -2 ** 30, 1], 1)
        self.check([2 ** 31 - 1] * 3 + [-2 ** 31 + 1], -2 ** 31 + 1)
        self.check([-2 ** 31] * 3 + [2 ** 31 - 2], 2 ** 31 - 2)

    def test_triples_are_cancelled_whatever_the_order(self):
        self.check([1, 2, 1, 2, 1, 2, 9], 9)
        self.check([9, 1, 2, 1, 2, 1, 2], 9)
        self.check([2, 1, 2, 1, 2, 1, 9], 9)

    def test_exhaustive_small_cases(self):
        for pool in ([0, 1], [0, 1, 2], [0, -1, 2], [0, 1, -2, 3]):
            for nums in tripled_arrays(pool):
                with self.subTest(nums=nums):
                    expected = counter_oracle(nums)
                    self.assertEqual(self.solve(nums), expected)
                    self.assertEqual(runs_oracle(nums), expected)

    def test_randomised_cases(self):
        rng = random.Random(1370)
        for _ in range(300):
            pool = rng.sample(range(-2 ** 31, 2 ** 31), rng.randint(1, 30))
            single = rng.choice(pool)
            nums = [value for value in pool if value != single] * 3 + [single]
            rng.shuffle(nums)
            with self.subTest(size=len(nums)):
                self.assertEqual(self.solve(nums), counter_oracle(nums))

    def test_randomised_boundary_pools(self):
        rng = random.Random(1371)
        for _ in range(100):
            pool = [-2 ** 31, 2 ** 31 - 1, 0, -1, 1] + [rng.randint(-1000, 1000)
                                                        for _ in range(rng.randint(0, 20))]
            pool = list(dict.fromkeys(pool))
            single = rng.choice(pool)
            nums = [value for value in pool if value != single] * 3 + [single]
            rng.shuffle(nums)
            with self.subTest(size=len(nums)):
                self.assertEqual(self.solve(nums), single)

    def test_constraint_sized(self):
        # A valid array has length 3k + 1, so 29998 is the largest legal size
        # below 3 * 10^4.
        size = 3 * 9999 + 1
        self.assertEqual(size, 29998)

        values = list(range(-9999, 0))
        nums = values * 3 + [2 ** 31 - 1]
        self.assertEqual(len(nums), size)
        self.check(nums, 2 ** 31 - 1)

        rng = random.Random(1372)
        pool = rng.sample(range(-2 ** 31, 2 ** 31), 9999)
        nums = pool * 3 + [-2 ** 31]
        rng.shuffle(nums)
        self.assertEqual(len(nums), size)
        self.assertEqual(self.solve(nums), -2 ** 31)

        nums = [value for value in range(9999) for _ in range(3)] + [12345]
        self.assertEqual(len(nums), size)
        self.assertEqual(self.solve(nums), 12345)

        nums = [2 ** 31 - 1] * 3 + [0, 0, 0] + [-2 ** 31] * 3 + [12345]
        self.assertEqual(self.solve(nums), 12345)


if __name__ == '__main__':
    unittest.main()
